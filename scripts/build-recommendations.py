#!/usr/bin/env python3
"""Generate book/appendix-recommendations.adoc from tagged recommendation blocks.

A recommendation block in a chapter looks like:

    // tag::rec-jwt-verification[]
    .Recommendation, dated 2026-09-16
    [NOTE.recommendation]
    ====
    ...
    ====
    // end::rec-jwt-verification[]

This script collects every `rec-*` tag, reads its date from the block title, and writes
an appendix that includes each block by tag, grouped by date, newest first. Mechanism
prose stays undated; only these blocks carry dates, versions and parameter values.

--check regenerates the appendix and exits 1 if that changed it.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BOOK = ROOT / "book"
OUT = BOOK / "appendix-recommendations.adoc"
TAG = re.compile(r"^// tag::(rec-[\w-]+)\[\]\s*$", re.M)
DATE = re.compile(r"^\.Recommendation, dated (\d{4}-\d{2}-\d{2})\s*$", re.M)


def collect() -> list[tuple[str, str, str, Path]]:
    found = []
    for p in sorted(BOOK.glob("track-*/*.adoc")):
        text = p.read_text(encoding="utf-8")
        cid = re.match(r"([A-K]\d{2})", p.name).group(1)
        for m in TAG.finditer(text):
            tag = m.group(1)
            end = text.find(f"// end::{tag}[]", m.end())
            block = text[m.end():end if end != -1 else None]
            d = DATE.search(block)
            if not d:
                sys.exit(f"{p}:{text[:m.start()].count(chr(10))+1}: {tag} has no '.Recommendation, dated YYYY-MM-DD' title")
            found.append((d.group(1), cid, tag, p))
    return found


def render(items: list[tuple[str, str, str, Path]]) -> str:
    lines = [
        "// GENERATED by scripts/build-recommendations.py. Do not edit; edit the chapter blocks.",
        "[appendix]",
        "[[recommendations]]",
        "= Recommendations, by date",
        "",
        "Every concrete recommendation in this book lives in a dated block inside its",
        "chapter, and is reproduced here so a reader can see at a glance how old each piece",
        "of advice is. Mechanism does not age; parameters, versions and product names do. If a",
        "date here is more than a year or two old, check the primary source before relying on it.",
        "",
    ]
    if not items:
        lines += ["No recommendation blocks have been written yet.", ""]
    for date in sorted({i[0] for i in items}, reverse=True):
        lines += [f"== {date}", ""]
        for d, cid, tag, p in sorted(items, key=lambda i: (i[1], i[2])):
            if d != date:
                continue
            rel = p.relative_to(BOOK).as_posix()
            lines += [f"=== From Chapter <<{cid},{cid}>>", "", f"include::{rel}[tag={tag}]", ""]
    return "\n".join(lines)


def main() -> int:
    text = render(collect())
    stale = not OUT.exists() or OUT.read_text(encoding="utf-8") != text
    if "--check" in sys.argv:
        # Regenerate, then fail if that changed anything, so a stale committed appendix
        # fails CI but a local run leaves the tree correct.
        OUT.write_text(text, encoding="utf-8")
        if stale:
            print(f"{OUT.relative_to(ROOT)} was stale and has been regenerated; commit it", file=sys.stderr)
            return 1
        print("recommendations appendix: up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
